class McpCatalogItem {
  final String id;
  final String name;
  final String description;
  final String category;
  final IconData icon;
  final McpServerType type;
  final String command;
  final List<String> args;
  final String url;
  final List<String> requiredEnvKeys;
  final Map<String, String> envHints;
  final Map<String, String> envKeyUrls;
  final List<String> requiredArgLabels;
  final bool isPopular;
  final List<String> tags;

  const McpCatalogItem({
    required this.id,
    required this.name,
    required this.description,
    required this.category,
    required this.icon,
    this.type = McpServerType.stdio,
    this.command = 'npx',
    this.args = const [],
    this.url = '',
    this.requiredEnvKeys = const [],
    this.envHints = const {},
    this.envKeyUrls = const {},
    this.requiredArgLabels = const [],
    this.isPopular = false,
    this.tags = const [],
  });

  McpServerConfig toConfig({
    Map<String, String> customEnv = const {},
    List<String>? customArgs,
  }) {
    return McpServerConfig(
      name: name,
      type: type,
      command: command,
      args: customArgs ?? args,
      url: url,
      isEnabled: true,
      env: customEnv,
    );
  }
}

